export type CopyKey = keyof typeof ja;
export const translate = (language: Language, key: CopyKey) => (language === 'ja' ? ja : en)[key];
export function errorText(language: Language, key: string) {
  if (key === 'ended') return translate(language, 'ended');
  return translate(language, key in ja ? (key as CopyKey) : 'unavailable');
}
